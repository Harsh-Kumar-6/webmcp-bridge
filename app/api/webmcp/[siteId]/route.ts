import { CORS_HEADERS } from "@/lib/cors";
import { loadSite } from "@/lib/store";
import { toJsonSchema } from "@/lib/tools";

export async function GET(req: Request, { params }: { params: Promise<{ siteId: string }> }) {
  const { siteId } = await params;
  const site = await loadSite(siteId);
  if (!site) return new Response("// site not found", { status: 404, headers: CORS_HEADERS });
  const tools = site.tools.map((t) => ({ name: t.name, description: t.description, inputSchema: toJsonSchema(t) }));
  const script = `// WebMCP tools for ${site.url}, generated by WebMCP Bridge.
(() => {
  const BRIDGE = ${JSON.stringify(new URL(req.url).origin)};
  const SITE_ID = ${JSON.stringify(site.siteId)};
  const TOOLS = ${JSON.stringify(tools)};
  const mc = document.modelContext ?? navigator.modelContext;
  if (!mc?.registerTool) {
    console.warn('[WebMCP Bridge] This browser does not expose WebMCP (modelContext).');
    return;
  }
  for (const tool of TOOLS) {
    mc.registerTool({
      ...tool,
      async execute(args) {
        const res = await fetch(BRIDGE + '/api/sites/' + SITE_ID + '/call', {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({ toolName: tool.name, input: args }),
        });
        const json = await res.json();
        const text = json.error ?? JSON.stringify(json.result);
        return { content: [{ type: 'text', text }], isError: !res.ok || json.ok === false };
      },
    });
  }
})();
`;
  return new Response(script, {
    headers: { ...CORS_HEADERS, "content-type": "application/javascript; charset=utf-8" },
  });
}
